/**
 * Resolve a postal code to coordinates
 */
export function resolvePostalCode(postalCode: string): { lat: number; lng: number; area: string } | null {
  const clean = postalCode.replace(/\D/g, '').padStart(6, '0');
  if (clean.length !== 6) return null;
  const sector = clean.substring(0, 2);
  return POSTAL_SECTOR_COORDINATES[sector] || null;
}
